"""Source-only tests. Set UFC6_TEST_GAME to a PRIVATE disposable fixture.

No game data is distributed with these tests. The test fixture is modified.
Set UFC6_EXPECTED_PACKET to the maintainer's PRIVATE verified patch packet to
also compare each generated byte with the independently game-tested patch.
"""
import base64
import json
import os
from pathlib import Path
import sys
import unittest
from unittest.mock import patch

sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import patcher_core as core


@unittest.skipUnless(os.environ.get('UFC6_TEST_GAME'),'Private disposable fixture not supplied')
class PatcherTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.root=Path(os.environ['UFC6_TEST_GAME']).resolve()
        cls.profile=core.load_profile(Path(__file__).resolve().parents[1])
        cls.backup=cls.root/core.BACKUP_NAME
        cls.expected=None
        if os.environ.get('UFC6_EXPECTED_PACKET'):
            cls.expected=json.loads(Path(os.environ['UFC6_EXPECTED_PACKET']).read_text())

    def setUp(self):
        self.running=patch.object(core,'game_running',return_value=False)
        self.running.start()

    def tearDown(self):
        self.running.stop()

    def assert_ranges(self, installed=False):
        with core.GameFiles(self.root,core.paths_for(self.profile),False) as files:
            for e in self.profile['entries']:
                expected=e['known_installed_sha256'] if installed else e['original_sha256']
                self.assertEqual(core.sha256(files.read(e)),expected)

    def test_01_reject_other_title_and_version_without_write(self):
        p=self.root/'sce_sys/param.json'
        original=p.read_bytes()
        try:
            for key,value in [('titleId','PPSA00000'),('contentVersion','01.007.000')]:
                data=json.loads(original);data[key]=value;p.write_text(json.dumps(data))
                with self.assertRaises(core.PatchError):core.run('install',self.root,self.profile)
                self.assertFalse(self.backup.exists())
                self.assert_ranges()
        finally:p.write_bytes(original)

    def test_02_generated_bytes_match_independently_verified_patch(self):
        with core.GameFiles(self.root,core.paths_for(self.profile),False) as files:
            plan=core.make_plan(files,self.profile)
        self.assertEqual(len(plan),430)
        if self.expected:
            for (e,old,new),known in zip(plan,self.expected['edits']):
                self.assertEqual((e['path'],e['offset']),(known['path'],known['offset']))
                self.assertEqual(old,base64.b64decode(known['original']))
                self.assertEqual(new,base64.b64decode(known['replacement']))

    def test_03_late_corruption_rejected_before_any_write(self):
        e=self.profile['entries'][-1]
        p=self.root/e['path']
        with p.open('r+b') as f:
            f.seek(e['offset']);old=f.read(e['length']);f.seek(e['offset']);f.write(bytes([old[0]^255])+old[1:])
        try:
            with self.assertRaises(core.PatchError):core.run('install',self.root,self.profile)
            self.assertFalse(self.backup.exists())
        finally:
            with p.open('r+b') as f:f.seek(e['offset']);f.write(old)
        self.assert_ranges()

    def test_04_running_game_refused(self):
        with patch.object(core,'game_running',return_value=True):
            with self.assertRaisesRegex(core.PatchError,'Close UFC 6'):
                core.run('install',self.root,self.profile)
        self.assertFalse(self.backup.exists())

    def test_05_write_failure_rolls_back_and_backup_recovers(self):
        real_write=core.GameFiles.write
        calls=[0]
        def fail_once(files,entry,data):
            calls[0]+=1
            if calls[0]==5:raise OSError('Simulated disk failure')
            return real_write(files,entry,data)
        with patch.object(core.GameFiles,'write',new=fail_once):
            with self.assertRaisesRegex(core.PatchError,'all attempted writes were restored'):
                core.run('install',self.root,self.profile)
        self.assert_ranges()
        self.assertTrue(self.backup.exists())
        self.assertEqual(len(core.read_backup(self.backup,self.profile)),430)
        self.assertIn('Installed',core.run('install',self.root,self.profile))
        self.assert_ranges(installed=True)

    def test_06_repeated_install_status_restore_and_reinstall(self):
        self.assertIn('Already installed',core.run('install',self.root,self.profile))
        self.assertIn('430/430',core.run('status',self.root,self.profile))
        self.assertIn('Restored',core.run('restore',self.root,self.profile))
        self.assert_ranges()
        self.assertIn('0/430',core.run('status',self.root,self.profile))
        core.run('install',self.root,self.profile)
        self.assert_ranges(installed=True)
        core.run('restore',self.root,self.profile)
        self.assert_ranges()

    def test_07_unknown_post_install_bytes_refuse_restore(self):
        e=self.profile['entries'][-1];p=self.root/e['path']
        with p.open('r+b') as f:
            f.seek(e['offset']);old=f.read(e['length']);f.seek(e['offset']);f.write(bytes([old[0]^255])+old[1:])
        try:
            with self.assertRaisesRegex(core.PatchError,'Game data changed'):
                core.run('restore',self.root,self.profile)
        finally:
            with p.open('r+b') as f:f.seek(e['offset']);f.write(old)
        self.assert_ranges()

    def test_08_local_backup_integrity_and_file_guards(self):
        import zipfile
        old=self.backup.read_bytes()
        try:
            # A modified manifest must be rejected before writes.
            with zipfile.ZipFile(self.backup) as archive:
                members={name:archive.read(name) for name in archive.namelist()}
            m=json.loads(members['manifest.json']);m['entries'][0]['offset']+=1
            members['manifest.json']=json.dumps(m).encode()
            with zipfile.ZipFile(self.backup,'w') as archive:
                for name,data in members.items():archive.writestr(name,data)
            with self.assertRaises(core.PatchError):core.run('restore',self.root,self.profile)
            self.assert_ranges()
        finally:self.backup.write_bytes(old)
        for relative in core.paths_for(self.profile):
            guard=b'FIXTURE GUARD: never change this.'
            with (self.root/relative).open('rb') as f:self.assertEqual(f.read(len(guard)),guard)


